/**
 * Generates GUIDE.md from src/guide/guide-content.ts so the written guide and the in-app
 * guide never drift apart. Run: bun run guide
 */
import { writeFileSync } from 'node:fs'
import {
  BROWSER_NOTES,
  type Control,
  KEYS,
  PAD_MODES,
  PANEL,
  QUICK_START,
  type Row,
  SAVING,
  SCREENS,
  SEQUENCER,
  WORKFLOWS,
} from '../src/guide/guide-content'

const cell = (text: string) => text.replaceAll('|', '\|')
const table = (rows: readonly Row[], head: [string, string], code = false) =>
  [
    `| ${head[0]} | ${head[1]} |`,
    '|---|---|',
    ...rows.map(([a, b]) => `| ${code ? `\`${a}\`` : `**${cell(a)}**`} | ${cell(b)} |`),
  ].join('\n')
const controls = (list: Control[]) => list.map((c) => `- **${c.name}** — ${c.text}`).join('\n')
const numbered = (list: string[]) => list.map((s, i) => `${i + 1}. ${s}`).join('\n')
const bullets = (list: string[]) => list.map((s) => `- ${s}`).join('\n')

const md = `# MPC 1000 — Browser Edition: User Guide

<!-- Generated by \`bun run guide\` from src/guide/guide-content.ts — edit that file, not this one. -->

The same guide is built into the app: press **?** or the **? GUIDE** button in the bottom strip.
That strip also describes any control you hover over.

## Contents

1. [Quick start](#quick-start)
2. [Every button on the machine](#every-button-on-the-machine)
3. [Pads and the MODE screens](#pads-and-the-mode-screens)
4. [Screens](#screens)
5. [Pattern sequencer](#pattern-sequencer)
6. [How to…](#how-to)
7. [Keyboard and MIDI](#keyboard-and-midi)
8. [Saving and exporting](#saving-and-exporting)

## Quick start

${numbered(QUICK_START)}

${bullets(BROWSER_NOTES)}

## Every button on the machine

${PANEL.map((g) => `### ${g.title}\n\n${controls(g.controls)}`).join('\n\n')}

## Pads and the MODE screens

Pads play sounds. Hitting near the top edge is louder; the computer keys Z X C V / A S D F / Q W E R / 1 2 3 4
are the four pad rows from bottom to top. There are four banks (A–D) of 16 pads — 64 sounds in total.

Press **MODE**, then a pad, to open the screen printed above it:

${table(PAD_MODES, ['Pad', 'Screen'])}

Pad modifiers: **FULL LEVEL** (always loudest), **16 LEVELS** (one sound over 16 velocities or pitches),
**TRACK MUTE** (pads mute tracks), **ERASE** (hold + pad deletes hits), **TAP TEMPO** held (note repeat).

## Screens

Select a field by clicking it, then turn the DATA wheel, scroll, or drag up/down. F1–F6 run the actions in the
boxes along the bottom of the screen. WINDOW enlarges the screen.

${SCREENS.map(
  (s) =>
    `### ${s.name}\n\n*Open:* ${s.open}\n\n${s.text}` +
    (s.fields.length ? `\n\n${table(s.fields, ['Field', 'What it does'])}` : '') +
    (s.fkeys.length ? `\n\n${table(s.fkeys, ['F-key', 'Action'], true)}` : ''),
).join('\n\n')}

## Pattern sequencer

The panel to the right of the MPC.

${controls(SEQUENCER)}

## How to…

${WORKFLOWS.map((w) => `### ${w.title}\n\n${numbered(w.steps)}`).join('\n\n')}

## Keyboard and MIDI

${table(KEYS, ['Key', 'Does'], true)}

MIDI controllers: notes 37–52 (C#1–E2, the MPC default) play PAD1–16 of the active bank with velocity. Choose a
device in MODE → PAD9 (MIDI/SYNC).

## Saving and exporting

${bullets(SAVING)}
`

writeFileSync(new URL('../GUIDE.md', import.meta.url), md)
console.log('GUIDE.md written')
